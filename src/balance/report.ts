export interface ReportOptions {
  levels: number[];
  maxAttempts: number;
  profiles?: Profile[];
  log?: (line: string) => void;
}

/** Runs every profile through the levels and writes the balancing report as markdown. */
export function balanceReport(o: ReportOptions): string {
  const log = o.log ?? (() => {});
  const profiles = o.profiles ?? PROFILES;
  const rows = new Map<Profile, LevelResult[]>();
  for (const profile of profiles) {
    const t0 = performance.now();
    const { results } = playCampaign({ profile, levels: o.levels, maxAttempts: o.maxAttempts, onLevel: (r) => log(`${profile} L${r.level}: ${r.failures} failures${r.won ? "" : " (stuck)"}`) });
    rows.set(profile, results);
    log(`${profile}: ${Math.round((performance.now() - t0) / 1000)} s`);
  }
  const out: string[] = [];
  out.push("# Balancing report", "");
  out.push(`Generated by \`npm run balance\` — levels ${o.levels[0]! + 1}–${o.levels.at(-1)! + 1}, at most ${o.maxAttempts} runs per level.`, "");
  out.push("Curves (`src/content/balance.ts`):", "", "```json", JSON.stringify(BALANCE, null, 2), "```", "");
  out.push("## Failed runs before the first win", "", "Target: about 10 at typical play (#2). `!` = gave up at the cap (stuck); `/n` = n of those runs farmed the previous level.", "");
  out.push(`| Level | Enemies | ${profiles.join(" | ")} |`, `|---|---|${profiles.map(() => "---").join("|")}|`);
  for (const i of o.levels) {
    const cells = profiles.map((p) => {
      const r = rows.get(p)!.find((x) => x.level === i + 1);
      return r ? `${r.failures}${r.farmed ? `/${r.farmed}` : ""}${r.won ? "" : "!"}` : "–";
    });
    out.push(`| ${i + 1} | ${enemyCount(LEVELS[i]!()).toLocaleString("de-DE")} | ${cells.join(" | ")} |`);
  }
  out.push("", "## Per level and profile", "", "| Profile | Level | Points/run | Run (s) | Research owned | Turrets | Best share |", "|---|---|---|---|---|---|---|");
  for (const p of profiles)
    for (const r of rows.get(p)!)
      out.push(`| ${p} | ${r.level} | ${Math.round(r.pointsPerRun).toLocaleString("de-DE")} | ${Math.round(r.seconds)} | ${r.research} | ${r.turrets} | ${Math.round(r.bestShare * 100)} % |`);
  out.push("", "## Simulation cost", "", "| Level | Blobs | Turrets | Mean step (ms) |", "|---|---|---|---|");
  for (const i of [9, 17, 24]) {
    const m = measureStep(i);
    out.push(`| ${i + 1} | ${m.blobs} | ${m.turrets} | ${m.ms.toFixed(2)} |`);
  }
  out.push("");
  return out.join("\n");
}

/** Mean simulation step of a level 40 s in, with 60 cannons of mid-game strength placed by the bot. */
export function measureStep(levelIndex: number): { blobs: number; turrets: number; ms: number } {
  const level = LEVELS[levelIndex]!();
  const base = deriveArsenal(["cannon"]);
  const arsenal: Arsenal = { turrets: { cannon: { ...base.turrets.cannon!, capacity: 60 } } };
  const w = createWorld({ ...level, goalEnergy: Number.MAX_SAFE_INTEGER }, arsenal, placeGreedy(level, arsenal, sampleFlow(level), ["cannon"]), 1);
  for (let t = 0; t < 30 * 40; t++) step(w);
  const n = 90;
  const t0 = performance.now();
  for (let t = 0; t < n; t++) step(w);
  return { blobs: w.enemies.length, turrets: w.turrets.length, ms: (performance.now() - t0) / n };
}

