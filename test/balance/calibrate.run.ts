// `npm run calibrate`: fits the per-level hit point factors and writes src/content/levelHp.ts. Takes long (an hour+).
import { it } from "vitest";
import { writeFileSync } from "node:fs";
import { calibrate } from "../../src/balance/calibrate.ts";

const levels = Number(process.env.BALANCE_LEVELS ?? 25);

it("calibration", () => {
  const { levelHp } = calibrate({
    profiles: ["specialist", "generalist"],
    levels: Array.from({ length: levels }, (_, i) => i),
    log: (l) => process.stdout.write(l + "\n"),
  });
  const rounded = levelHp.map((f) => Number(f.toPrecision(3)));
  writeFileSync(
    "src/content/levelHp.ts",
    "// Generated by `npm run calibrate` (src/balance/calibrate.ts, #11). Do not edit by hand: rerun the calibration.\n" +
      `export const LEVEL_HP: readonly number[] = ${JSON.stringify(rounded)};\n`,
  );
  process.stdout.write(`\nwritten: src/content/levelHp.ts ${JSON.stringify(rounded)}\n`);
}, 6 * 3_600_000);
